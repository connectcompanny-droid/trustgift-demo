  const normalize = value => String(value).replace(/\s+/g, " ").trim();
  const reverse = {};
  for (const [language, dictionary] of Object.entries(translations)) {
    reverse[language] = new Map();
    for (const [source, localized] of Object.entries(dictionary)) {
      const key = normalize(localized);
      if (!reverse[language].has(key)) reverse[language].set(key, source);
    }
  }

  let language = "EN";
  const textSources = new WeakMap();
  const attributeSources = new WeakMap();

  function sourceKey(value) {
    const key = normalize(value);
    return reverse[language]?.get(key) ?? key;
  }

  function matchTemplate(value, dictionary) {
    const normalizedValue = normalize(value);
    for (const [template, localized] of Object.entries(dictionary)) {
      const placeholders = [...template.matchAll(/\{(\w+)\}/g)];
      if (!placeholders.length) continue;

      let expression = "";
      let offset = 0;
      for (const placeholder of placeholders) {
        expression += template.slice(offset, placeholder.index).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
        expression += "(.+?)";
        offset = placeholder.index + placeholder[0].length;
      }
      expression += template.slice(offset).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
      const match = normalizedValue.match(new RegExp(`^${expression}$`));
      if (match) {
        return {
          localized,
          parameters: Object.fromEntries(placeholders.map((placeholder, index) => [
            placeholder[1],
            match[index + 1]
          ]))
        };
      }
    }
    return null;
  }

  function translate(value, parameters = {}) {
    let key = sourceKey(value);
    const dictionary = translations[language] ?? {};
    let result = dictionary[key];
    let replacements = parameters;
    if (!result) {
      const match = matchTemplate(key, dictionary);
      if (match) {
        result = match.localized;
        replacements = {
          ...Object.fromEntries(Object.entries(match.parameters).map(([name, value]) => [
            name,
            translate(value)
          ])),
          ...parameters
        };
      }
    }
    result ??= key;
    for (const [name, replacement] of Object.entries(replacements)) {
      result = result.replaceAll(`{${name}}`, String(replacement));
    }
    return result;
  }

  function translateTextNode(node) {
    if (node.parentElement?.closest("[data-i18n-ignore], code, .chat-message")) return;
    let source = textSources.get(node);
    if (!source) {
      const raw = node.nodeValue;
      const leading = raw.match(/^\s*/)?.[0] ?? "";
      const trailing = raw.match(/\s*$/)?.[0] ?? "";
      const end = trailing.length ? raw.length - trailing.length : raw.length;
      source = { key: sourceKey(raw.slice(leading.length, end)), leading, trailing };
      textSources.set(node, source);
    }
    const translated = `${source.leading}${translate(source.key)}${source.trailing}`;
    if (node.nodeValue !== translated) node.nodeValue = translated;
  }

  function translateAttribute(element, attribute) {
    const value = element.getAttribute(attribute);
    if (value === null) return;
    let sources = attributeSources.get(element);
    if (!sources) {
      sources = new Map();
      attributeSources.set(element, sources);
    }
    if (!sources.has(attribute)) sources.set(attribute, sourceKey(value));
    const translated = translate(sources.get(attribute));
    if (value !== translated) element.setAttribute(attribute, translated);
  }

  function translateTree(root) {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) translateTextNode(walker.currentNode);
    if (root.nodeType === Node.ELEMENT_NODE) {
      for (const attribute of ["placeholder", "aria-label", "title"]) translateAttribute(root, attribute);
    }
    root.querySelectorAll?.("[placeholder], [aria-label], [title]").forEach(element => {
      for (const attribute of ["placeholder", "aria-label", "title"]) translateAttribute(element, attribute);
    });
  }

  function setLanguage(nextLanguage, persist = true) {
    if (!["EN", "FR", "ES"].includes(nextLanguage)) return;
    language = nextLanguage;
    document.documentElement.lang = { EN: "en", FR: "fr", ES: "es" }[language];
    document.querySelectorAll(".language").forEach(button => {
      const selected = button.dataset.lang === language;
      button.classList.toggle("selected", selected);
      button.setAttribute("aria-pressed", String(selected));
    });
    translateTree(document.body);
    document.title = translate(titleSource);
    if (persist && location.protocol !== "file:") {
      try {
        localStorage.setItem("trustgift-language", language);
      } catch (error) {
        console.warn("Could not save the language preference.", error);
      }
    }
    document.dispatchEvent(new CustomEvent("trustgift-language-change", { detail: { language } }));
  }

  let storedLanguage = "EN";
  if (location.protocol !== "file:") {
    try {
      storedLanguage = localStorage.getItem("trustgift-language") ?? "EN";
    } catch (error) {
      console.warn("Could not read the saved language preference.", error);
    }
  }
  language = ["EN", "FR", "ES"].includes(storedLanguage) ? storedLanguage : "EN";
  const titleSource = sourceKey(document.title);
  setLanguage(language, false);

  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === "characterData") translateTextNode(record.target);
      for (const node of record.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else if (node.nodeType === Node.ELEMENT_NODE) translateTree(node);
      }
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true });

  window.TRUSTGIFT_I18N = {
    getLanguage: () => language,
    getLocale: () => ({ EN: "en", FR: "fr-FR", ES: "es-ES" }[language]),
    setLanguage,
    translate
  };
